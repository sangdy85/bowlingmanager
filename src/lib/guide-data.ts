function applyPublicGuideMetadata(article: GuideArticle): GuideArticle {
  const metadata = PUBLIC_GUIDE_METADATA[article.slug];
  if (!metadata) return article;
  return {
    ...article,
    ...metadata,
    content: article.content.replace(/\n## 마지막 검토일\s*\n[\s\S]*$/, '').trimEnd(),
  };
}


